import {beforeAll,afterAll,afterEach,it,expect,vi} from 'vitest';
import {randomUUID} from 'node:crypto';
import {db} from '../../src/server/db';
import {encrypt} from '../../src/server/crypto';
import {tickSchedules} from '../../src/server/scheduler';
import {runProduction} from '../../src/worker/pipeline';
import {checkDeadlines,reconcile} from '../../src/worker/reconcile';
import {productionQueue,closeQueues} from '../../src/server/queue';
import {OpenAIAdapter} from '../../src/providers/openai';
import {fixtureScript} from '../fixtures';
import {mkdir,readFile} from 'node:fs/promises';
import path from 'node:path';
import {runMedia} from '../../src/render/ffmpeg';
import {putAsset} from '../../src/server/storage';
import {estimateProject} from '../../src/server/estimates';
let workspaceId:string,channelId:string;
beforeAll(async()=>{
 workspaceId=(await db.workspace.create({data:{name:'TEST schedule stages'}})).id;
 channelId=(await db.contentChannel.create({data:{workspaceId,name:'TEST staged channel',topic:'Testing',mode:'MANUAL',budgetCents:10000}})).id;
 await db.aIProvider.create({data:{workspaceId,name:'TEST stages',encryptedKey:encrypt('test-only')}});
});
afterEach(()=>vi.restoreAllMocks());
afterAll(async()=>{await db.workspace.delete({where:{id:workspaceId}});await closeQueues();await db.$disconnect();});
it('checkpoints research, releases the worker, resumes once due and keeps the paid result',async()=>{
 const now=new Date(),rule=await db.scheduleRule.create({data:{workspaceId,channelId,name:'TEST two stages',topic:randomUUID(),nextRunAt:new Date(+now-1000),productionDelayMinutes:60,approvalBufferMinutes:30,maxRuns:1}});
 await Promise.all([tickSchedules(now,workspaceId),tickSchedules(now,workspaceId)]);
 const occurrence=await db.scheduledOccurrence.findFirstOrThrow({where:{scheduleId:rule.id},include:{project:{include:{jobs:true}}}}),p=occurrence.project,job=p.jobs[0];
 expect(+p.productionAt!-+p.scheduledAt!).toBe(3600000);
 expect(+p.publishAt!-+p.deadlineAt!).toBe(1800000);
 await db.videoProject.update({where:{id:p.id},data:{productionConfig:{researchEnabled:true}}});
 await db.researchSource.createMany({data:[{projectId:p.id,url:'https://example.com/source',title:'Test source',excerpt:'This is supplied test evidence, not a live research request.'}]});
 const research=vi.spyOn(OpenAIAdapter.prototype,'structured').mockResolvedValue({summary:'Test brief',claims:[],policyFlags:[],recommendations:[]});
 const script=vi.spyOn(OpenAIAdapter.prototype,'script').mockResolvedValue({...structuredClone(fixtureScript),title:randomUUID()});
 await runProduction(job.id);
 expect(script).not.toHaveBeenCalled();expect(research).toHaveBeenCalledTimes(1);
 expect(await db.productionJob.findUnique({where:{id:job.id}})).toMatchObject({status:'QUEUED',step:'RESEARCH_COMPLETED',availableAt:p.productionAt,attempts:0,queueVersion:1});
 const checkpoint=await db.videoProject.findUniqueOrThrow({where:{id:p.id}});
 expect(checkpoint.researchCompletedAt).not.toBeNull();expect(checkpoint.productionStartedAt).toBeNull();
 await runProduction(job.id);expect(script).not.toHaveBeenCalled();
 await reconcile(workspaceId);expect(await productionQueue().getJob(job.id+'-1')).toBeUndefined();
 const due=new Date(Date.now()-1000);await db.videoProject.update({where:{id:p.id},data:{productionAt:due}});await db.productionJob.update({where:{id:job.id},data:{availableAt:due}});
 await Promise.all([runProduction(job.id),runProduction(job.id)]);
 expect(script).toHaveBeenCalledTimes(1);expect(research).toHaveBeenCalledTimes(1);
 const finished=await db.videoProject.findUniqueOrThrow({where:{id:p.id}});
 expect(finished.status).toBe('SCRIPT_READY');expect(finished.completedAt).not.toBeNull();expect(finished.productionStartedAt).not.toBeNull();
 expect(finished.researchCompletedAt).toEqual(checkpoint.researchCompletedAt);
 expect(await db.costUsage.count({where:{projectId:p.id,status:'COMPLETED'}})).toBe(2);
});
it('notifies once for a missed deadline, including a late completed video, and preserves on-time completions',async()=>{
 const deadline=new Date(Date.now()-60000),data={workspaceId,channelId,title:'TEST deadline',topic:'TEST',topicHash:'TEST',deadlineAt:deadline};
 const late=await db.videoProject.create({data:{...data,status:'AWAITING_APPROVAL',completedAt:new Date()}}),onTime=await db.videoProject.create({data:{...data,status:'AWAITING_APPROVAL',completedAt:new Date(+deadline-1000)}});
 const before=await db.notification.count({where:{workspaceId,title:'Video quá hạn chuẩn bị'}});
 await Promise.all([checkDeadlines(workspaceId),checkDeadlines(workspaceId)]);
 expect((await db.videoProject.findUniqueOrThrow({where:{id:late.id}})).deadlineMissedAt).toEqual(deadline);
 expect((await db.videoProject.findUniqueOrThrow({where:{id:onTime.id}})).deadlineMissedAt).toBeNull();
 expect(await db.notification.count({where:{workspaceId,title:'Video quá hạn chuẩn bị'}})).toBe(before+1);
 expect((await db.videoProject.findUniqueOrThrow({where:{id:late.id}})).status).toBe('AWAITING_APPROVAL');
});
it('renders chart scenes without image/video providers and estimates only missing assets',async()=>{
 const directory=path.resolve('artifacts/pipeline-graphics-fixture');await mkdir(directory,{recursive:true});const voice=path.join(directory,'voice.wav');
 await runMedia('ffmpeg',['-v','error','-y','-f','lavfi','-i','sine=frequency=440:duration=4.8','-c:a','pcm_s16le',voice]);const bytes=await readFile(voice);
 const script=structuredClone(fixtureScript);for(const scene of script.scenes)scene.graphic={kind:'STEPS',title:'KIỂM THỬ ĐỒ HỌA',unit:'',items:[{label:'Bước thứ nhất',value:1},{label:'Bước thứ hai',value:2}],sourceUrl:null};
 const p=await db.videoProject.create({data:{workspaceId,channelId,title:'TEST chart pipeline',topic:randomUUID(),topicHash:randomUUID(),intent:'VIDEO',revision:1,targetDuration:10,productionConfig:{visualMode:'HYBRID'},script:{create:{data:script}},jobs:{create:{idempotencyKey:randomUUID()}}},include:{jobs:true}});
 for(const scene of script.scenes){const storageKey=workspaceId+'/'+p.id+'/r1/voice-'+scene.scene_order+'.wav';await putAsset(storageKey,bytes,'audio/wav');await db.generatedAsset.create({data:{workspaceId,projectId:p.id,revision:1,sceneOrder:scene.scene_order,kind:'AUDIO',storageKey,mimeType:'audio/wav',bytes:bytes.length,duration:4.8}});}
 await db.aIProvider.updateMany({where:{workspaceId},data:{enabled:false}});
 const estimate=await estimateProject(workspaceId,p.id);expect(estimate.items.find(i=>i.category==='IMAGE')?.cents).toBe(0);expect(estimate.items.find(i=>i.category==='VIDEO')?.cents).toBe(0);expect(estimate.items.find(i=>i.category==='TTS')?.cents).toBe(0);
 const image=vi.spyOn(OpenAIAdapter.prototype,'image'),speech=vi.spyOn(OpenAIAdapter.prototype,'speech');
 await runProduction(p.jobs[0].id);const rendered=await db.videoProject.findUniqueOrThrow({where:{id:p.id}});
 expect(rendered.status).toBe('AWAITING_APPROVAL');expect(rendered.qaScore).toBe(100);expect(image).not.toHaveBeenCalled();expect(speech).not.toHaveBeenCalled();
 expect(await db.costUsage.count({where:{projectId:p.id,category:{in:['IMAGE','VIDEO','TTS']}}})).toBe(0);
});
